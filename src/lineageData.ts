interface AdjacencyEdge {
  toId: string
  relationEn: string
  relationAm: string
}

function buildGraph(): Map<string, AdjacencyEdge[]> {
  const graph = new Map<string, AdjacencyEdge[]>()

  for (const person of Object.values(LINEAGE_PEOPLE)) {
    if (!graph.has(person.id)) graph.set(person.id, [])

    // Father edge
    if (person.fatherId && LINEAGE_PEOPLE[person.fatherId]) {
      graph.get(person.id)!.push({
        toId: person.fatherId,
        relationEn: `son of ${LINEAGE_PEOPLE[person.fatherId].nameEn}`,
        relationAm: `የ${LINEAGE_PEOPLE[person.fatherId].nameAm} ልጅ`,
      })
      if (!graph.has(person.fatherId)) graph.set(person.fatherId, [])
      graph.get(person.fatherId)!.push({
        toId: person.id,
        relationEn: `father of ${person.nameEn}`,
        relationAm: `የ${person.nameAm} አባት`,
      })
    }

    // Mother edge
    if (person.motherId && LINEAGE_PEOPLE[person.motherId]) {
      graph.get(person.id)!.push({
        toId: person.motherId,
        relationEn: `child of ${LINEAGE_PEOPLE[person.motherId].nameEn}`,
        relationAm: `የ${LINEAGE_PEOPLE[person.motherId].nameAm} ልጅ`,
      })
      if (!graph.has(person.motherId)) graph.set(person.motherId, [])
      graph.get(person.motherId)!.push({
        toId: person.id,
        relationEn: `mother of ${person.nameEn}`,
        relationAm: `የ${person.nameAm} እናት`,
      })
    }

    // Spouse edges
    for (const spouseId of person.spouseIds) {
      if (LINEAGE_PEOPLE[spouseId]) {
        graph.get(person.id)!.push({
          toId: spouseId,
          relationEn: `married to ${LINEAGE_PEOPLE[spouseId].nameEn}`,
          relationAm: `ከ${LINEAGE_PEOPLE[spouseId].nameAm} ጋር የተጋባ/ች`,
        })
      }
    }

    // Children edges
    for (const childId of person.childrenIds) {
      if (LINEAGE_PEOPLE[childId]) {
        graph.get(person.id)!.push({
          toId: childId,
          relationEn: `parent of ${LINEAGE_PEOPLE[childId].nameEn}`,
          relationAm: `የ${LINEAGE_PEOPLE[childId].nameAm} ወላጅ`,
        })
      }
    }
  }

  // Add covenantal / mentorship links for characters connected spiritually or historically:
  const spiritualLinks: [string, string, string, string][] = [
    ['melchizedek', 'abraham', 'blessed by Melchizedek in Genesis 14', 'በዘፍጥረት 14 በመልከ ጼዴቅ የተባረከ'],
    ['queen_of_sheba', 'solomon', 'visited for divine wisdom in 1 Kings 10', 'በ1 ነገሥት 10 ጥበቡን ለማየት የጎበኘችው'],
    ['ebed_melech', 'david', 'royal servant in the Davidic court', 'በዳዊት ዙፋን ቤተ መንግሥት ያገለገለ'],
    ['ethiopian_eunuch', 'jesus', 'worshiped & received Christ through Isaiah 53', 'በኢሳይያስ 53 ወንጌል ክርስቶስን ያመነ'],
    ['timothy', 'jesus', 'apostolic disciple & minister of Christ', 'የክርስቶስ ደቀ መዝሙርና አገልጋይ'],
    ['cornelius', 'jesus', 'embraced faith in Christ through Peter', 'በጴጥሮስ ስብከት በክርስቶስ ያመነ'],
  ]

  for (const [from, to, relEn, relAm] of spiritualLinks) {
    if (graph.has(from) && graph.has(to)) {
      graph.get(from)!.push({ toId: to, relationEn: relEn, relationAm: relAm })
      graph.get(to)!.push({ toId: from, relationEn: `connected to ${LINEAGE_PEOPLE[from]?.nameEn}`, relationAm: `ከ${LINEAGE_PEOPLE[from]?.nameAm} ጋር የተገናኘ` })
    }
  }

  return graph
}

const LINEAGE_GRAPH = buildGraph()

/**
 * Breadth-First-Search (BFS) shortest path between any two individuals in Scripture.
 */
export function findSixDegreesPath(fromId: string, toId: string): PathStep[] {
  if (fromId === toId) {
    const person = LINEAGE_PEOPLE[fromId]
    return person ? [{ person }] : []
  }

  const queue: { currentId: string; path: { id: string; relEn?: string; relAm?: string }[] }[] = [
    { currentId: fromId, path: [{ id: fromId }] },
  ]
  const visited = new Set<string>([fromId])

  while (queue.length > 0) {
    const { currentId, path } = queue.shift()!

    const neighbors = LINEAGE_GRAPH.get(currentId) || []
    for (const neighbor of neighbors) {
      if (neighbor.toId === toId) {
        // Found target!
        const fullPath = [...path, { id: neighbor.toId }]
        // Map back relations
        const result: PathStep[] = []
        for (let i = 0; i < fullPath.length; i++) {
          const stepPerson = LINEAGE_PEOPLE[fullPath[i].id]
          if (!stepPerson) continue
          let relationToNextEn: string | undefined
          let relationToNextAm: string | undefined

          if (i < fullPath.length - 1) {
            const nextId = fullPath[i + 1].id
            const edge = LINEAGE_GRAPH.get(fullPath[i].id)?.find((e) => e.toId === nextId)
            relationToNextEn = edge?.relationEn
            relationToNextAm = edge?.relationAm
          }

          result.push({
            person: stepPerson,
            relationToNextEn,
            relationToNextAm,
          })
        }
        return result
      }

      if (!visited.has(neighbor.toId)) {
        visited.add(neighbor.toId)
        queue.push({
          currentId: neighbor.toId,
          path: [...path, { id: neighbor.toId, relEn: neighbor.relationEn, relAm: neighbor.relationAm }],
        })
      }
    }
  }

  return []
}

/**
 * Return chapters where the Lineage Web badge should be proactively featured in the reader.
 */
export function isLineageChapter(bookNr: number, chapterNr: number): boolean {
  // Matthew 1 (Genealogy of Christ)
  if (bookNr === 40 && chapterNr === 1) return true
  // Luke 3 (Ancestry from Adam to Christ)
  if (bookNr === 42 && chapterNr === 3) return true
  // Ruth 4 (Genealogy of Perez to David)
  if (bookNr === 8 && chapterNr === 4) return true
  // Genesis 5 (Adam to Noah)
  if (bookNr === 1 && chapterNr === 5) return true
  // Genesis 10 (Table of Nations / Cush / Nimrod)
  if (bookNr === 1 && chapterNr === 10) return true
  // Genesis 11 (Shem to Abraham)
  if (bookNr === 1 && chapterNr === 11) return true
  // 1 Chronicles 1 (Patriarchs)
  if (bookNr === 13 && chapterNr === 1) return true
  return false
}

