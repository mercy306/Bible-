const SAGA_PROGRESS_KEY = 'bible:saga-progress'

export interface SagaProgressState {
  completedScenes: string[]
  lastSceneId: string | null
}

export function getSagaProgress(): SagaProgressState {
  try {
    const raw = localStorage.getItem(SAGA_PROGRESS_KEY)
    if (!raw) return { completedScenes: [], lastSceneId: null }
    const parsed = JSON.parse(raw)
    return {
      completedScenes: Array.isArray(parsed.completedScenes) ? parsed.completedScenes : [],
      lastSceneId: typeof parsed.lastSceneId === 'string' ? parsed.lastSceneId : null,
    }
  } catch {
    return { completedScenes: [], lastSceneId: null }
  }
}

export function saveSagaProgress(state: SagaProgressState): void {
  try {
    localStorage.setItem(SAGA_PROGRESS_KEY, JSON.stringify(state))
  } catch {
    // Ignore storage quota errors
  }
}

export function isSceneCompleted(sceneId: string): boolean {
  const p = getSagaProgress()
  return p.completedScenes.includes(sceneId)
}

export function toggleSceneCompleted(sceneId: string): SagaProgressState {
  const current = getSagaProgress()
  const exists = current.completedScenes.includes(sceneId)
  const nextCompleted = exists
    ? current.completedScenes.filter((id) => id !== sceneId)
    : [...current.completedScenes, sceneId]

  const nextState: SagaProgressState = {
    completedScenes: nextCompleted,
    lastSceneId: sceneId,
  }
  saveSagaProgress(nextState)
  return nextState
}

export function getActProgress(actId: number): { completed: number; total: number; percent: number } {
  const act = SAGA_ACTS.find((a) => a.id === actId)
  if (!act) return { completed: 0, total: 0, percent: 0 }
  const p = getSagaProgress()
  const completed = act.scenes.filter((s) => p.completedScenes.includes(s.id)).length
  const total = act.scenes.length
  const percent = total > 0 ? Math.round((completed / total) * 100) : 0
  return { completed, total, percent }
}

export function getTotalSagaProgress(): { completed: number; total: number; percent: number } {
  const p = getSagaProgress()
  let total = 0
  let completed = 0
  for (const act of SAGA_ACTS) {
    total += act.scenes.length
    for (const s of act.scenes) {
      if (p.completedScenes.includes(s.id)) completed++
    }
  }
  const percent = total > 0 ? Math.round((completed / total) * 100) : 0
  return { completed, total, percent }
}
